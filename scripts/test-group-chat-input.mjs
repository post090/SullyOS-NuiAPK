import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
mkdirSync('output/group-chat-input', { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
const errors = [], modelCalls = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (request.url().includes('/chat/completions')) modelCalls.push(request.url()); });
const prefsKey = 'sully-chat-input-preferences-v1';
try {
    await page.goto('http://127.0.0.1:5177/test/fixtures/group-chat-input.html');
    await page.getByText('群聊列表', { exact: true }).waitFor();
    await page.evaluate(async key => {
        const { DB } = await import('/utils/db.ts');
        await DB.saveGroup({ id: 'qa-emoji-group', name: '表情匹配回归群', members: [], createdAt: 1 });
        await DB.saveEmojiCategory({ id: 'qa-emoji-category', name: '回归分类' });
        await DB.saveEmoji('亲亲回归', '/assets/sar/caian-chibi.png', 'qa-emoji-category');
        localStorage.setItem(key, JSON.stringify({ emojiSuggestions: true, sendButtonGenerates: true, enterToSend: false, autoReply: true }));
        localStorage.setItem('os_api_config', JSON.stringify({ baseUrl: 'http://127.0.0.1:5177/qa-group-api/v1', apiKey: 'qa-only', model: 'qa-only' }));
    }, prefsKey);
    await page.route('**/qa-group-api/**', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ choices: [{ message: { role: 'assistant', content: '' } }] }) }));
    await page.reload();
    const open = () => page.getByText('表情匹配回归群', { exact: true }).click();
    await open();
    const input = page.locator('textarea'), region = page.getByRole('region', { name: '表情包联想' });
    await input.fill('亲亲回归');
    await region.waitFor();
    const composer = () => page.locator('.sully-chat-inputbar > div:first-child').evaluate(el => el.contains(document.querySelector('textarea')));
    assert(await composer(), 'legacy composer selector stays valid in real group chat');
    await page.screenshot({ path: 'output/group-chat-input/suggestions-390.png' });
    await page.getByRole('button', { name: '发送表情：亲亲回归', exact: true }).click();
    await page.waitForFunction(async () => {
        const { DB } = await import('/utils/db.ts');
        return (await DB.getGroupMessages('qa-emoji-group')).length === 1;
    });
    const messages = await page.evaluate(async () => {
        const { DB } = await import('/utils/db.ts'); return DB.getGroupMessages('qa-emoji-group');
    });
    assert.equal(messages[0].type, 'emoji');
    assert.equal(messages[0].content, '/assets/sar/caian-chibi.png');
    assert.equal(messages[0].role, 'user');
    assert.equal(await input.inputValue(), '亲亲回归', 'real group send handler preserves draft');
    assert.equal(await input.evaluate(el => document.activeElement === el), true);
    await region.waitFor({ state: 'hidden' });
    const settings = async () => {
        await page.getByRole('button', { name: '聊天功能', exact: true }).click();
        await page.getByRole('button', { name: '群设置', exact: true }).click();
    };
    await settings();
    await page.getByLabel('表情包智能匹配', { exact: true }).uncheck();
    await page.getByRole('button', { name: '保存修改', exact: true }).click();
    assert.deepEqual(await page.evaluate(key => JSON.parse(localStorage.getItem(key)), prefsKey), { emojiSuggestions: false, sendButtonGenerates: true, enterToSend: false, autoReply: true });
    await input.fill('亲亲');
    assert.equal(await region.count(), 0);
    await page.reload(); await open();
    await input.fill('亲亲'); assert.equal(await region.count(), 0);
    await settings();
    assert.equal(await page.getByLabel('表情包智能匹配', { exact: true }).isChecked(), false);
    await page.getByLabel('表情包智能匹配', { exact: true }).check();
    await page.getByRole('button', { name: '保存修改', exact: true }).click();
    await input.focus(); await region.waitFor();
    await page.setViewportSize({ width: 320, height: 740 });
    await page.screenshot({ path: 'output/group-chat-input/suggestions-320.png' });
    assert(await composer());
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.deepEqual(modelCalls, [], 'suggesting and sending do not automatically request a model');
    // Enter preference and full settings use the actual GroupChat send path.
    await input.fill('换行测试'); await input.press('Enter');
    assert.equal(await input.inputValue(), '换行测试\n');
    await settings();
    await page.getByLabel('回车发送文字', { exact: true }).check();
    await page.getByRole('button', { name: '保存修改', exact: true }).click();
    await input.fill('自动回复测试'); await input.press('Enter');
    await page.waitForFunction(() => document.querySelector('textarea').value === '');
    assert.equal(await page.getByRole('button', { name: '取消自动回复' }).count(), 0, 'focus blocks countdown');
    const blur = () => page.locator('div.overflow-y-auto.overflow-x-hidden.pt-6').click({ position: { x: 8, y: 8 } });
    await blur();
    await page.getByRole('button', { name: '取消自动回复' }).waitFor();
    await page.waitForRequest('**/qa-group-api/**');
    await page.getByRole('button', { name: '生成回复', exact: true }).waitFor();
    assert.equal(modelCalls.length, 1, 'one director request after successful send and ready delay');
    await input.fill('取消回复测试'); await input.press('Enter');
    await page.waitForFunction(() => document.querySelector('textarea').value === '');
    await blur(); await page.getByRole('button', { name: '取消自动回复' }).click();
    await page.waitForTimeout(2200);
    assert.equal(modelCalls.length, 1, 'cancel prevents auto generation');
    await input.fill('保留手动生成草稿'); await blur();
    await page.getByRole('button', { name: '生成回复', exact: true }).click();
    await page.waitForFunction(() => !document.querySelector('[aria-label="正在生成回复"]'));
    assert.equal(await input.inputValue(), '保留手动生成草稿');
    assert.equal(modelCalls.length, 2, 'composer generation uses group director');
    await input.fill('退出前发送'); await input.press('Enter');
    await page.waitForFunction(() => document.querySelector('textarea').value === '');
    await blur(); await page.getByRole('button', { name: '取消自动回复' }).waitFor();
    await page.locator('.sully-chat-back').click();
    await page.getByText('群聊列表', { exact: true }).waitFor();
    await page.waitForTimeout(2200);
    assert.equal(modelCalls.length, 2, 'leaving group cancels pending generation');
    assert.deepEqual(errors, []);
    console.log('PASS: real GroupChat suggestions, persistence, all shared preferences, Enter/newline, generation button, automatic reply, cancel and exit; two local mocked director requests.');
} catch (error) {
    await page.screenshot({ path: 'output/group-chat-input/failure.png' });
    console.error((await page.locator('body').innerText()).slice(-1600));
    throw error;
} finally { await browser.close(); }
