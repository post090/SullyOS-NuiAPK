import { execSync } from 'node:child_process';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// esbuild options shared by every bundled worker, including the service worker that
// `vite build` bundles again with the static cache manifest (scripts/static-cache-build.ts).

// 与 vite.config.ts 注入同一组构建常量：utils/buildInfo.ts 的依赖链（db.ts →
// databaseOpenDiagnostics.ts → buildInfo.ts）会把它们拖进 worker bundle。esbuild
// 不 define 的话 bundle 里会留下裸标识符，Cloudflare 模块 Worker 上传的 10021
// 预执行校验直接拒收（Uncaught ReferenceError: __BUILD_BRANCH__ is not defined）。
// 非 git 环境退化成 'unknown'，与 vite 侧行为一致。
const UTC8_OFFSET_MS = 8 * 60 * 60 * 1000;
function formatBuildTimeUtc8(date = new Date()) {
  const utc8Date = new Date(date.getTime() + UTC8_OFFSET_MS);
  return `${utc8Date.toISOString().slice(0, 19).replace('T', ' ')} UTC+8`;
}
function readBranch() {
  if (process.env.GITHUB_REF_NAME) return process.env.GITHUB_REF_NAME;
  try {
    return execSync('git rev-parse --abbrev-ref HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return 'unknown';
  }
}
function readCommit() {
  if (process.env.GITHUB_SHA) return process.env.GITHUB_SHA.slice(0, 7);
  try {
    return execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return 'unknown';
  }
}

// The bundled workers use only Web Crypto (globalThis.crypto.subtle) and have
// zero Node crypto imports, so they run on CF Workers with no compatibility
// flags and no runtime polyfill.
export const workerBundleOptions = {
  format: 'esm',
  target: 'es2022',
  platform: 'neutral',
  bundle: true,
  minify: false,
  conditions: ['worker', 'browser', 'import', 'default'],
  // @capacitor/* 不能标 external：external 会在 bundle 顶上留一行裸导入，而 Cloudflare
  // 的模块 Worker 上传（面板粘贴 / 自更新 / wrangler deploy）不认裸导入，一律 10021
  // 拒收（2026-10 实际发生过：mcpClient.ts 引入 Capacitor 后所有更新全挂）。db.ts →
  // mcpClient.ts 的 import 链会把它拖进 bundle，但 worker 永远跑不到原生分支——alias
  // 到假身，让死分支保持死。以后再冒出别的 @capacitor/* 导入，esbuild 会当场报
  // resolve 失败，比静默塞进裸导入强。
  alias: {
    '@capacitor/core': resolve(root, 'scripts/worker-stubs/capacitor-core.ts'),
  },
  // cloudflare:* 是运行时自带的内置模块（amsg 用 cloudflare:workers 的 DurableObject
  // 基类）。它们不在 node_modules 里，不标 external 的话 esbuild 会当成缺失依赖报错。
  external: ['cloudflare:*'],
  define: {
    __BUILD_BRANCH__: JSON.stringify(readBranch()),
    __BUILD_COMMIT__: JSON.stringify(readCommit()),
    __BUILD_TIME__: JSON.stringify(formatBuildTimeUtc8()),
  },
};

